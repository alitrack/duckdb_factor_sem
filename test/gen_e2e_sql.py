#!/usr/bin/env python3
"""Emit test/test_factor.sql.

Two parts:
1. cfa_cov on the ORACLE case-0 covariance (test/factor_ref.json[0]). This
   S's MLE is independently verified by the Rust unit test against scipy
   L-BFGS-B, so checking the built binary's output against these reference
   values verifies: the C-API glue, JSON marshaling, covariance parsing, and
   that the binary matches the verified library. Loadings compared in |.|
   (eigenvector sign arbitrary); psi + fit indices sign-invariant.
2. cfa_fit (raw data path) smoke test: correct p/q/n/df, finite chi2/cfi.
"""
import json

with open("test/factor_ref.json") as fh:
    cases = json.load(fh)
c0 = cases[0]
p, q, n = c0["p"], c0["q"], c0["n"]
S = c0["S"]
lam_ref = c0["lambda_ref"]
psi_ref = c0["psi_ref"]
chi2_ref = c0["chi2"]
cfi_ref = c0["cfi"]
tli_ref = c0["tli"]
rmsea_ref = c0["rmsea"]
llm_ref = c0["ll_model"]

# flat cov string: n p s00 s01 ... s(pp-1)
flat = " ".join(f"{v:.12f}" for row in S for v in row)
cov_str = f"{n} {p} {flat}"

lines = []
lines.append("-- duckdb_factor_sem v0.1.0 end-to-end test (DuckDB-native).")
lines.append("-- Each check emits (label, ok); final row reports n_fail; the")
lines.append("-- runner (test/run_factor.sh) asserts n_fail = 0.")
lines.append("--")
lines.append("-- Part 1: cfa_cov on the oracle case-0 covariance (S). This S's")
lines.append("-- MLE is independently verified by the Rust unit test against the")
lines.append("-- scipy L-BFGS-B oracle, so this checks the built binary +")
lines.append("-- C-API glue + JSON + covariance parsing against a known value.")
lines.append("-- Loadings compared in |.| (eigenvector sign is arbitrary);")
lines.append("-- psi + fit indices are sign-invariant and compared directly.")
lines.append("-- Part 2: cfa_fit (raw-data path) smoke test.")
lines.append("")
lines.append("LOAD '/mnt/d/wsl2/duckdb_factor_sem/target/release/factor_sem_ext.duckdb_extension';")
lines.append("")
lines.append("CREATE OR REPLACE MACRO num(j, key) AS json_extract(j, '$.' || key)::DOUBLE;")
lines.append("CREATE OR REPLACE MACRO ok(a, r, tol) AS")
lines.append("  CASE WHEN a IS NULL OR r IS NULL THEN false")
lines.append("       WHEN ABS(a - r) <= tol * GREATEST(1.0, ABS(r)) THEN true ELSE false END;")
lines.append("")
lines.append(f"CREATE OR REPLACE TEMP TABLE fit_cov AS SELECT cfa_cov('{cov_str}', '{q}') AS j;")
lines.append("")
# Part 2 raw data (p=4, n=40) for cfa_fit smoke — 1-factor data, n large
# enough for the EM to converge (n=12 was near-singular and returned NULL).
# test/raw40.txt is generated by test/gen_raw.py (seed 42).
with open("test/raw40.txt") as fh:
    raw = fh.read().strip()
lines.append(f"CREATE OR REPLACE TEMP TABLE fit_raw AS SELECT cfa_fit('{raw}', '1') AS j;")
lines.append("")
lines.append("CREATE OR REPLACE TEMP TABLE checks AS")
lines.append(f"  SELECT 'cov.meta.p'  AS label, (num((SELECT j FROM fit_cov),'p') = {p}) AS p")
lines.append(f"  UNION ALL SELECT 'cov.meta.q', (num((SELECT j FROM fit_cov),'q') = {q})")
lines.append(f"  UNION ALL SELECT 'cov.meta.n', (num((SELECT j FROM fit_cov),'n') = {n})")
lines.append(f"  UNION ALL SELECT 'cov.meta.df', (num((SELECT j FROM fit_cov),'df') = {p*(p+1)//2 - (p*q+p)})")
lines.append(f"  UNION ALL SELECT 'cov.chi2',  ok(num((SELECT j FROM fit_cov),'chi2'),  {chi2_ref},   1e-3)")
lines.append(f"  UNION ALL SELECT 'cov.cfi',   ok(num((SELECT j FROM fit_cov),'cfi'),   {cfi_ref},   1e-3)")
lines.append(f"  UNION ALL SELECT 'cov.tli',   ok(num((SELECT j FROM fit_cov),'tli'),   {tli_ref},   1e-3)")
lines.append(f"  UNION ALL SELECT 'cov.rmsea', ok(num((SELECT j FROM fit_cov),'rmsea'), {rmsea_ref}, 1e-3)")
lines.append(f"  UNION ALL SELECT 'cov.ll',    ok(num((SELECT j FROM fit_cov),'ll_model'), {llm_ref}, 1e-3)")
for i in range(p):
    lines.append(
        f"  UNION ALL SELECT 'cov.lam[{i}]',  ok(num((SELECT j FROM fit_cov), 'lambda[{i}][0]')::DOUBLE, "
        f"{abs(lam_ref[i][0])}, 2e-4)"
    )
for i in range(p):
    lines.append(
        f"  UNION ALL SELECT 'cov.psi[{i}]', ok(num((SELECT j FROM fit_cov), 'psi[{i}]')::DOUBLE, "
        f"{psi_ref[i]}, 2e-4)"
    )
# Part 2: raw-data smoke (cfa_fit)
lines.append(f"  UNION ALL SELECT 'raw.meta.p', (num((SELECT j FROM fit_raw),'p') = 4)")
lines.append(f"  UNION ALL SELECT 'raw.meta.q', (num((SELECT j FROM fit_raw),'q') = 1)")
lines.append(f"  UNION ALL SELECT 'raw.meta.n', (num((SELECT j FROM fit_raw),'n') = 40)")
lines.append("  UNION ALL SELECT 'raw.chi2_finite', (num((SELECT j FROM fit_raw),'chi2') IS NOT NULL)")
lines.append("  UNION ALL SELECT 'raw.cfi_range', (num((SELECT j FROM fit_raw),'cfi') IS NOT NULL)")
# error paths -> NULL
lines.append("  UNION ALL SELECT 'err.q0',     (cfa_fit('1 2 3 | 2 3 4 | 3 4 5', '0') IS NULL)")
lines.append("  UNION ALL SELECT 'err.qneg',   (cfa_fit('1 2 3 | 2 3 4 | 3 4 5', '-1') IS NULL)")
lines.append("  UNION ALL SELECT 'err.badd',   (cfa_fit('a b c | d e f | g h i', '1') IS NULL)")
lines.append("  UNION ALL SELECT 'err.q_gt_p', (cfa_fit('1 2 | 3 4 | 5 6', '2') IS NULL)")
lines.append("  UNION ALL SELECT 'err.cov_n',  (cfa_cov('1 2 1.0 0.5 0.5 1.0', '1') IS NULL);")
lines.append("")
lines.append("SELECT")
lines.append("  COUNT(*) AS n_checks,")
lines.append("  COUNT(*) FILTER (WHERE NOT p) AS n_fail,")
lines.append("  string_agg(label, ', ' ORDER BY label) FILTER (WHERE NOT p) AS failing")
lines.append("FROM checks;")

with open("test/test_factor.sql", "w") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"wrote test/test_factor.sql ({len(lines)} lines)")
print(f"cov chi2_ref={chi2_ref} cfi={cfi_ref} ll={llm_ref}")
